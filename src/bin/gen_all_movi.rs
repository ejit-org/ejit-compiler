

use std::{io::Write, process::Command};

fn main() {
    let mut f = std::fs::File::create("asm-test/all_movi.s").unwrap();
    let _ = writeln!(f, "# Generate all the vector immediate combinations.");
    let _ = writeln!(f, "# This is a generated file, do not edit it manually.");
    let _ = writeln!(f, "# The file is generated by the `gen_all_movi.rs` script.");
    let _ = writeln!(f, "# The file is used by the `movi` instruction in the `gen_movi.rs` script.");
    let _ = writeln!(f, " .text");
    
    let base = 0x0f000400_u64;
    // see https://developer.arm.com/documentation/ddi0602/2024-03/SIMD-FP-Instructions/MOVI--Move-Immediate--vector--
    for q in 0..2 {
        for op in 0..2 {
            for cmode in 0..16 {
                // let abc = 0;
                let defgh = 0;
                for abc in 0..8 {
                //     for defgh in 0..32 {
                        let value = base | q << 30 | op << 29 | abc << 16 | cmode << 12 | defgh << 5;
                        let _ = writeln!(f, " .word 0x{:08x}", value);
                //     }
                }
            }
        }
    }
    drop(f);

    Command::new("aarch64-linux-gnu-as")
        .args(["asm-test/all_movi.s", "-o", "/tmp/1.o"])
        .status()
        .expect("Failed to run gas");
    let output = Command::new("aarch64-linux-gnu-objdump")
        .args(["-D", "/tmp/1.o"])
        .output().unwrap();
    let out = String::from_utf8_lossy(&output.stdout);
    println!("{}", out);
}
